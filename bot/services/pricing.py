"""Цены подписки (Блок «Баланс»). Все суммы — в КОПЕЙКАХ (никаких float у денег).

Модель: первая позиция (устройство ИЛИ резервное подключение) стоит
`price_first_rub` — это пол тарифа. Каждая следующая позиция прибавляется по
своей цене. Чем длиннее срок — тем больше скидка. Рубли из конфига, скидки и
округление — здесь.
"""
from __future__ import annotations

from dataclasses import dataclass

from bot.config import settings

# Срок (мес) → скидка в %. Итог округляется ВНИЗ до 10 ₽ — в пользу юзера,
# чтобы цены были «круглыми» (база 90₽: 3 мес 240, 6 мес 450, 12 мес 810).
TERM_DISCOUNTS: dict[int, int] = {1: 0, 3: 10, 6: 15, 12: 25}

# Срок словами. Живёт рядом со скидками, чтобы кнопки покупки, выдача админом
# и уведомления автопродления называли срок ОДИНАКОВО: юзер должен узнавать
# в списании ровно то, что выбирал.
TERM_LABELS: dict[int, str] = {1: "месяц", 3: "3 мес", 6: "полгода", 12: "год"}

# Дни, прибавляемые за «месяц» подписки.
DAYS_PER_MONTH = 30

# Потолок конструктора тарифа. Живёт здесь, а не в хендлере: правило обязано
# действовать на ВСЕХ путях — и на покупке, и на смене тарифа. Проверка
# безопасности 20.08.2026 нашла, что смена его не соблюдала, а callback_data
# подделывается руками.
MAX_TARIFF_DEVICES = 10
MAX_TARIFF_BYPASS = 10


def tariff_ceiling(max_devices: int, max_bypass: int) -> tuple[int, int]:
    """Потолки конструктора для юзера с такими текущими лимитами.

    Обычно 10/10, но если админ выставил больше — показываем и разрешаем
    честно, а не срезаем молча: иначе смена тарифа тихо даунгрейдила бы
    выданное админом.
    """
    return (
        max(MAX_TARIFF_DEVICES, max_devices),
        max(MAX_TARIFF_BYPASS, max_bypass),
    )

_ROUND_TO = 10 * 100  # 10 ₽ в копейках

# Границы одного пополнения, ₽. Живут здесь, а не в экранах: их спрашивают бот,
# мини-приложение и проверка суммы, введённой руками, — три места на одно
# правило разъезжаются первыми.
DEPOSIT_MIN_RUB, DEPOSIT_MAX_RUB = 10, 100_000


def topup_need_rub(missing_kopeks: int) -> int:
    """Сколько предложить пополнить, чтобы покупка точно прошла.

    Округляем ВВЕРХ до десяти рублей и не опускаемся ниже минимального
    пополнения: «не хватает 3.50 ₽» на кнопке выглядит ошибкой, а пополнение
    ровно впритык не пройдёт, если провайдер округлит по-своему.
    """
    rub = -(-missing_kopeks // 100)              # копейки вверх до рубля
    rounded = -(-rub // 10) * 10                 # и вверх до десятки
    return max(DEPOSIT_MIN_RUB, min(DEPOSIT_MAX_RUB, rounded))

# Бонус за способ пополнения, % к зачисляемой сумме (этап D). Смысл — вести
# юзера к способу, который дешевле обходится сервису: карта 9 % и СБП 8 % самые
# дорогие, доплачивать за них нельзя. У звёзд своя наценка 25 %, и бонус поверх
# неё был бы взаимоисключающим.
DEPOSIT_BONUS_PERCENT: dict[str, int] = {
    "cryptobot": 4,
    "platega": 0,
    "stars": 0,
}

# Способ человеческими словами — для истории операций. Юзер видит «через
# CryptoBot», а не служебный ключ, которым способ называется в коде.
DEPOSIT_METHOD_LABELS: dict[str, str] = {
    "cryptobot": "через CryptoBot",
    "platega": "картой",
    "stars": "звёздами",
}


def deposit_bonus_kopeks(amount_kopeks: int, method: str) -> int:
    """Надбавка к зачислению за способ пополнения.

    Неизвестный способ — ноль: новый провайдер не должен начать раздавать
    бонусы просто потому, что его забыли внести в таблицу.
    """
    return amount_kopeks * DEPOSIT_BONUS_PERCENT.get(method, 0) // 100


def stars_for_kopeks(kopeks: int) -> int:
    """Во сколько звёзд обходится сумма в копейках, с наценкой за способ.

    Округление ВВЕРХ до целой звезды: дробной звезды не бывает, а округление
    вниз дарило бы юзеру долю звезды на каждой покупке.
    """
    with_markup = kopeks * (100 + settings.star_markup_percent)
    return -(-with_markup // (100 * settings.star_price_kopeks))


def monthly_price_kopeks(max_devices: int, max_bypass: int) -> int:
    """₽/мес тарифа. Первая позиция — `price_first_rub`, каждая следующая
    прибавляется: устройство +`price_extra_device_rub`, резервное подключение
    +`price_extra_bypass_rub`.

    Первой считается устройство, если оно есть; если устройств ноль — первое
    подключение. Тариф без единой позиции (0+0) не существует — за ним стоит
    ошибка вызывающего.

    Формула только складывает, поэтому дешевле пола тариф быть не может. У
    прежней база покрывала позиции, а отказ от них вычитался, и при
    base < сумма доплат тариф уходил в минус — за этим приходилось следить
    отдельным правилом. Правило исчезло вместе с вычитанием.
    """
    if max_devices + max_bypass < 1:
        raise ValueError("тариф без устройств и обходов не продаётся")  # wording: ok
    if max_devices >= 1:
        rub = (
            settings.price_first_rub
            + (max_devices - 1) * settings.price_extra_device_rub
            + max_bypass * settings.price_extra_bypass_rub
        )
    else:
        rub = (
            settings.price_first_rub
            + (max_bypass - 1) * settings.price_extra_bypass_rub
        )
    return rub * 100


def term_price_kopeks(monthly_kopeks: int, months: int) -> int:
    """Цена за срок со скидкой TERM_DISCOUNTS, округление вниз до 10 ₽."""
    discount = TERM_DISCOUNTS.get(months, 0)
    raw = monthly_kopeks * months * (100 - discount) // 100
    return max(_ROUND_TO, raw // _ROUND_TO * _ROUND_TO)


def fmt_rub(kopeks: int) -> str:
    """Копейки → строка «90 ₽» / «−90.50 ₽» (копейки видны, только если есть)."""
    sign = "−" if kopeks < 0 else ""
    kopeks = abs(kopeks)
    rub, kop = divmod(kopeks, 100)
    return f"{sign}{rub}.{kop:02d} ₽" if kop else f"{sign}{rub} ₽"


def convert_remaining(seconds: int, old_monthly_kopeks: int, new_monthly_kopeks: int) -> int:
    """Сколько секунд останется, если перевести остаток старого тарифа в новый.

    Смысл: неиспользованное время не сгорает и не возвращается деньгами — оно
    пересчитывается по стоимости. Дороже тариф — меньше времени, дешевле —
    больше. Одна формула работает в обе стороны, поэтому не нужны ни возвраты
    на баланс, ни отдельное правило против дешёвого апгрейда.

    Обе цены — БАЗОВЫЕ (`monthly_price_kopeks`), без скидки за срок. Скидка
    участвовать не может: иначе годовые 25 % множились бы на каждой смене
    тарифа — купил год со скидкой, «сменил» на тот же самый тариф и вышел с
    486 днями вместо 365.

    Округление ВНИЗ: качели между тарифами обязаны терять время, а не печатать
    его. Пары «туда-обратно» стережёт тест round_trip_never_gains.
    """
    if seconds <= 0:
        return 0
    if new_monthly_kopeks <= 0:
        raise ValueError("тариф без цены не существует")  # wording: ok
    return seconds * old_monthly_kopeks // new_monthly_kopeks


# ── Готовые тарифы ───────────────────────────────────────────────────────────
#
# Витрина вместо конструктора в лоб (решение Влада 22.08.2026). Причина: шесть
# кнопок «−/+» — это вопрос «сколько тебе устройств?», на который человек,
# пришедший купить VPN, ещё не знает ответа. Три готовые строки он читает и
# выбирает, а конструктор остаётся за кнопкой для тех, кто знает точно.
#
# Составы подобраны так, чтобы каждый следующий делал устройство дешевле —
# это и есть та самая выгода, и она НАСТОЯЩАЯ, а не зачёркнутая цена:
# 120 ₽ за одно устройство, 80 ₽ за каждое из двух, 67 ₽ за каждое из четырёх.


@dataclass(frozen=True)
class Preset:
    """Готовый тариф витрины. `key` едет в callback_data, поэтому короткий."""

    key: str
    emoji: str
    name: str
    devices: int
    bypass: int
    hint: str


PRESETS: tuple[Preset, ...] = (
    Preset("solo", "📱", "Один", 1, 1, "телефон или компьютер"),
    Preset("duo", "💻", "Два устройства", 2, 1, "телефон и компьютер"),
    Preset("family", "👪", "Семейный", 4, 2, "себе и близким"),
)


def preset_by_key(key: str) -> Preset | None:
    for preset in PRESETS:
        if preset.key == key:
            return preset
    return None


def per_device_kopeks(monthly_kopeks: int, devices: int) -> int:
    """Во сколько обходится ОДНО устройство тарифа, ₽/мес.

    Ноль устройств — ноль: делить не на что, а строка «цена за устройство» у
    тарифа без устройств смысла не имеет.

    Округляем до целого рубля, как и цену месяца: «по 67.50 ₽ за устройство»
    в ряду круглых чисел читается как сбой, а не как выгода. Это ориентир, а не
    сумма списания, — точная цена тарифа стоит рядом.
    """
    if devices <= 0:
        return 0
    per = monthly_kopeks / devices
    return int(per // 100 * 100 + (100 if per % 100 >= 50 else 0))


def best_value_key() -> str:
    """Тариф витрины с самой низкой ценой за устройство.

    Считается, а не проставлен руками: поменяются цены в настройках — метка
    переедет сама. Метка, которую забыли передвинуть за ценами, — это уже не
    подсказка, а обман.
    """
    return min(
        PRESETS,
        key=lambda p: per_device_kopeks(
            monthly_price_kopeks(p.devices, p.bypass), p.devices
        ) or 10 ** 9,
    ).key


def month_of_term_kopeks(total_kopeks: int, months: int) -> int:
    """Во сколько обходится месяц при оплате за срок целиком.

    Нужна на каждой кнопке срока: «1080 ₽ за год» человек сравнивать не умеет,
    а «90 ₽/мес» рядом со «120 ₽/мес за месяц» — умеет сразу.

    Округляем до ЦЕЛОГО рубля, к ближайшему: «106.66 ₽/мес» на кнопке выглядит
    сломанной ценой, а не выгодой. Точная сумма при этом всегда рядом — цена
    срока целиком стоит на той же кнопке, и по ней сходится копейка в копейку.
    """
    if months <= 0:
        return total_kopeks
    per_month = total_kopeks / months
    return int(per_month // 100 * 100 + (100 if per_month % 100 >= 50 else 0))
