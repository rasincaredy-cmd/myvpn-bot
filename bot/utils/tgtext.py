"""Работа с потолком длины сообщения Telegram.

Сообщение длиннее 4096 символов Telegram не принимает вовсе — не обрезает, а
отказывает. Экран, который собирается из списка (пиры сервера, ссылки на
конфиги, история), рано или поздно этот потолок пробьёт, и человек увидит не
длинный список, а ничего.

Найдено аудитом 20.08.2026 дважды: выдача ссылок ломалась на четвёртой локации,
экран трафика сервера — примерно на 34-м пире (на тот момент их было 14 и 10).
"""
from __future__ import annotations

# Потолок текстового сообщения Telegram.
TG_TEXT_LIMIT = 4096


def fit_to_message(
    lines: list[str],
    *,
    limit: int = TG_TEXT_LIMIT,
    note: str = "\n\n<i>…показаны первые {shown} из {total} — остальное не влезло в сообщение.</i>",
) -> str:
    """Склеивает строки, обрезая список так, чтобы сообщение прошло.

    Обрезка НИКОГДА не молчит: сколько строк показано и сколько всего, пишется
    прямо в сообщении. Молча укороченный список читается как «больше ничего
    нет» — и по нему принимают решения.

    Первая строка считается заголовком и не выбрасывается никогда: без неё
    непонятно, что вообще на экране.
    """
    if not lines:
        return ""
    text = "\n".join(lines)
    if len(text) <= limit:
        return text

    head, rest = lines[0], lines[1:]
    # Место под заголовок и под саму приписку об обрезке.
    budget = limit - len(head) - len(note.format(shown=len(rest), total=len(rest))) - 2
    kept: list[str] = []
    size = 0
    for line in rest:
        if size + len(line) + 1 > budget:
            break
        kept.append(line)
        size += len(line) + 1
    return (
        head + "\n" + "\n".join(kept)
        + note.format(shown=len(kept), total=len(rest))
    )
