"""Дизайн-система экранов бота (Блок «Облик», 20.08.2026).

Зачем модуль: до него каждый экран верстался как придётся — где буллеты, где
абзац курсивом на шестьдесят слов, где «Моя подписка», а где «Подписка».
Правила должны быть кодом, иначе через месяц бот расползается обратно.

Направление выбрано Владом: **строки-иконки**. Экран собирается из четырёх
частей, любая кроме заголовка необязательна:

    <заголовок>          🎫 <b>Подписка</b>
    <lead>               одна живая фраза о главном
    <факты>              📱 Устройства — <b>2 из 3</b>
    <note>               одна строка-подсказка
    <справка>            свёрнутая цитата, разворачивается тапом

Длинные объяснения уезжают в `help_block` — сворачиваемую цитату. Так справка
остаётся на месте (юзер её найдёт), но не занимает экран у того, кто её уже
читал.

В Telegram нет моноширинного текста в обычных сообщениях, поэтому колонок и
выравнивания по правому краю здесь нет и быть не может: ритм держится длиной
строк, жирностью значений и раскладкой кнопок.
"""
from __future__ import annotations

from typing import Iterable

from aiogram.utils.text_decorations import html_decoration as _html

# Больше пяти фактов — это уже простыня. Ограничение намеренно жёсткое: если
# новый экран в него не влезает, значит он делает два дела и его надо делить.
MAX_FACTS = 5


def safe(value: object | None) -> str:
    """Чужой текст → безопасный для HTML-разметки.

    Обязателен для всего, что пришло не от нас: имя из профиля Telegram, метка
    устройства, название локации. Имя вида «<Вася>» без экранирования делает
    сообщение непарсимым, Telegram его не принимает — и человек не может
    запустить бота ни разу (найдено 20.08.2026).
    """
    if value is None:
        return ""
    return _html.quote(str(value))


def title(emoji: str, name: str) -> str:
    """Заголовок экрана: одна эмодзи + существительное жирным.

    Без «Мои»/«Моя»: раздел обязан называться одинаково в кнопке меню и в
    заголовке — человек ищет глазами то же слово, на которое нажал.
    """
    return f"{emoji} <b>{safe(name)}</b>"


def fact(emoji: str, name: str, value: object) -> str:
    """Строка-факт: `📱 Устройства — <b>2 из 3</b>`.

    Значение всегда жирное и всегда справа: глаз сканирует столбик значений,
    не перечитывая названия.
    """
    return f"{emoji} {name} — <b>{safe(value)}</b>"


def help_block(heading: str, body: str) -> str:
    """Свёрнутая справка. Разворачивается тапом, свёрнутая занимает одну строку.

    Тег отдаём aiogram (`<blockquote expandable>`), чтобы не держать разметку
    Telegram в двух местах.
    """
    return _html.expandable_blockquote(f"{heading}\n{body}")


def screen(
    head: str,
    *,
    lead: str | None = None,
    facts: Iterable[str] = (),
    note: str | None = None,
    help: str | None = None,
) -> str:
    """Собирает экран из частей, пропуская пустые.

    Пустая часть не оставляет дыры: блоки склеиваются через одну пустую строку
    ПОСЛЕ отбрасывания пустых, иначе экран без lead выглядел бы разреженнее
    экрана с ним.
    """
    rows = list(facts)
    if len(rows) > MAX_FACTS:
        raise ValueError(
            f"на экране {len(rows)} фактов, максимум {MAX_FACTS} — "
            "значит экран делает два дела и его надо делить"
        )
    blocks = [head, lead, "\n".join(rows) if rows else None, note, help]
    return "\n\n".join(b for b in blocks if b)
